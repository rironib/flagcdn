let currentCode = 'us';
let currentCountry = 'United States';
let currentFormat = 'html';
let currentSize = 64;
let allFlags = FLAGS_DATA;

function loadAndRenderFlags() {
    allFlags.sort((a, b) => a.name.localeCompare(b.name));
    renderFlagsGrid(allFlags);

    // Restore saved flag selection from localStorage after rendering
    try {
        const savedCode = localStorage.getItem('selectedFlagCode');
        const savedName = localStorage.getItem('selectedFlagName');
        if (savedCode && savedName) {
            updateHeroDisplay(savedCode, savedName, false);
        }
    } catch (e) {}
}

function renderFlagsGrid(flags) {
    const grid = document.getElementById('flags-grid');
    if (!grid) return;

    grid.innerHTML = flags.map(flag => {
        const escapedName = flag.name.replace(/"/g, '&quot;');
        const jsName = flag.name.replace(/'/g, "\'");
        return `
        <div class="flag-card group cursor-pointer bg-surface-card hover:bg-surface-container-low border border-border-subtle hover:border-primary p-4 rounded-xl flex flex-col items-center text-center transition-all duration-150 hover:-translate-y-1 hover:shadow-lg"
            data-code="${flag.code}" data-name="${escapedName}" onclick="selectFlag('${flag.code}', '${jsName}')">
            <div class="relative w-14 h-14 mb-3 flex items-center justify-center">
                <img alt="${escapedName} Flag"
                    class="rounded-full shadow-sm group-hover:scale-105 transition-transform" height="48"
                    src="${flag.path}" width="48" loading="lazy">
            </div>
            <span
                class="text-label-caps font-label-caps text-on-surface font-bold bg-surface-container px-2 py-0.5 rounded">${flag.code_upper}</span>
            <span class="text-body-sm font-body-sm text-on-surface-variant mt-1.5 truncate w-full"
                title="${escapedName}">${escapedName}</span>
            <span
                class="mt-2 text-label-caps font-label-caps text-primary opacity-0 group-hover:opacity-100 transition-opacity flex items-center gap-1">
                <span class="material-symbols-outlined text-xs">content_copy</span> Copy
            </span>
        </div>`;
    }).join('');
}

function renderSnippet() {
    const display = document.getElementById('code-snippet-display');
    if (!display) return;
    const url = `https://rironib.github.io/flagcdn/flags/${currentCode}.svg`;

    if (currentFormat === 'html') {
        display.innerHTML = `&lt;<span class="text-indigo-400">img</span> <span class="text-sky-300">src</span>=<span class="text-emerald-300">"${url}"</span> <span class="text-sky-300">alt</span>=<span class="text-emerald-300">"${currentCountry} Flag"</span> <span class="text-sky-300">width</span>=<span class="text-amber-300">"${currentSize}"</span> <span class="text-sky-300">height</span>=<span class="text-amber-300">"${currentSize}"</span> /&gt;`;
    } else if (currentFormat === 'react') {
        display.innerHTML = `&lt;<span class="text-indigo-400">Image</span> <span class="text-sky-300">src</span>=<span class="text-emerald-300">"${url}"</span> <span class="text-sky-300">alt</span>=<span class="text-emerald-300">"${currentCountry} Flag"</span> <span class="text-sky-300">width</span>={<span class="text-amber-300">${currentSize}</span>} <span class="text-sky-300">height</span>={<span class="text-amber-300">${currentSize}</span>} /&gt;`;
    } else if (currentFormat === 'markdown') {
        display.innerHTML = `![<span class="text-emerald-300">${currentCountry} Flag</span>](<span class="text-sky-300">${url}</span>)`;
    } else if (currentFormat === 'url') {
        display.innerHTML = `<span class="text-emerald-300">${url}</span>`;
    }
}

function getRawSnippetText() {
    const url = `https://rironib.github.io/flagcdn/flags/${currentCode}.svg`;
    if (currentFormat === 'html') {
        return `<img src="${url}" alt="${currentCountry} Flag" width="${currentSize}" height="${currentSize}" />`;
    } else if (currentFormat === 'react') {
        return `<Image src="${url}" alt="${currentCountry} Flag" width={${currentSize}} height={${currentSize}} />`;
    } else if (currentFormat === 'markdown') {
        return `![${currentCountry} Flag](${url})`;
    } else {
        return url;
    }
}

function setFormat(format) {
    currentFormat = format;
    const tabs = ['html', 'react', 'markdown', 'url'];
    tabs.forEach(t => {
        const btn = document.getElementById(`tab-${t}`);
        if (!btn) return;
        if (t === format) {
            btn.className = "px-2.5 py-1 text-label-caps font-label-caps rounded bg-primary text-on-primary font-medium transition-all";
        } else {
            btn.className = "px-2.5 py-1 text-label-caps font-label-caps rounded text-on-surface-variant hover:text-on-surface transition-all";
        }
    });
    renderSnippet();
}

function changePreviewSize(size) {
    currentSize = size;
    const flagImg = document.getElementById('live-flag-image');
    if (flagImg) {
        flagImg.width = size;
        flagImg.height = size;
    }
    const label = document.getElementById('current-size-label');
    if (label) label.textContent = `Size: ${size} × ${size} px`;

    // Update button highlights
    document.querySelectorAll('.size-pill').forEach(btn => {
        if (btn.textContent.trim() === `${size}px`) {
            btn.className = "size-pill px-3 py-1 text-label-caps font-label-caps rounded-md border border-primary bg-primary text-on-primary transition-all";
        } else {
            btn.className = "size-pill px-3 py-1 text-label-caps font-label-caps rounded-md border border-border-subtle hover:border-primary transition-all";
        }
    });

    renderSnippet();
}

function updateHeroDisplay(code, countryName, saveToStorage = true) {
    currentCode = code;
    currentCountry = countryName;

    if (saveToStorage) {
        try {
            localStorage.setItem('selectedFlagCode', code);
            localStorage.setItem('selectedFlagName', countryName);
        } catch (e) { }
    }

    // Update interactive preview
    const previewImg = document.getElementById('live-flag-image');
    if (previewImg) {
        previewImg.src = `flags/${code}.svg`;
        previewImg.alt = `${countryName} Flag`;
    }

    // Update text details by direct element IDs
    const headline = document.getElementById('current-country-name');
    if (headline) headline.textContent = countryName;

    const isoBadge = document.getElementById('current-iso-badge');
    if (isoBadge) isoBadge.textContent = `ISO: ${code.toUpperCase()}`;

    renderSnippet();
}

function selectFlag(code, countryName) {
    updateHeroDisplay(code, countryName, true);

    // Copy automatically
    copyTextToClipboard(getRawSnippetText(), `Copied ${countryName} (${code.toUpperCase()}) code!`);
}

function copySnippet() {
    copyTextToClipboard(getRawSnippetText(), 'CDN Code snippet copied!');
}

function copyTextToClipboard(text, message) {
    if (navigator.clipboard) {
        navigator.clipboard.writeText(text).then(() => triggerToast(message));
    } else {
        triggerToast(message);
    }
}

function triggerToast(message) {
    const toast = document.getElementById('toast');
    const toastText = document.getElementById('toast-text');
    const copyBtnLabel = document.getElementById('copy-label');
    const copyIcon = document.getElementById('copy-icon');

    if (!toast || !toastText) return;

    toastText.textContent = message;
    toast.classList.remove('translate-y-20', 'opacity-0');
    toast.classList.add('translate-y-0', 'opacity-100');

    if (copyBtnLabel && copyIcon) {
        copyBtnLabel.textContent = "Copied!";
        copyIcon.textContent = "check";
    }

    setTimeout(() => {
        toast.classList.remove('translate-y-0', 'opacity-100');
        toast.classList.add('translate-y-20', 'opacity-0');
        if (copyBtnLabel && copyIcon) {
            copyBtnLabel.textContent = "Copy Code";
            copyIcon.textContent = "content_copy";
        }
    }, 2500);
}

function filterFlags() {
    const searchInput = document.getElementById('flag-search');
    if (!searchInput) return;
    const query = searchInput.value.toLowerCase().trim();
    const cards = document.querySelectorAll('.flag-card');
    let visibleCount = 0;

    cards.forEach(card => {
        const name = (card.getAttribute('data-name') || '').toLowerCase();
        const code = (card.getAttribute('data-code') || '').toLowerCase();

        if (name.includes(query) || code.includes(query)) {
            card.style.display = '';
            visibleCount++;
        } else {
            card.style.display = 'none';
        }
    });

    const noResults = document.getElementById('no-results');
    if (noResults) {
        if (visibleCount === 0) {
            noResults.classList.remove('hidden');
        } else {
            noResults.classList.add('hidden');
        }
    }
}

// Initialize on DOM load or immediately if DOM is ready
if (document.readyState === 'loading') {
    window.addEventListener('DOMContentLoaded', loadAndRenderFlags);
} else {
    loadAndRenderFlags();
}

// Keyboard shortcut for Cmd+K search focus
window.addEventListener('keydown', (e) => {
    if ((e.metaKey || e.ctrlKey) && e.key === 'k') {
        e.preventDefault();
        const searchInput = document.getElementById('flag-search');
        if (searchInput) {
            searchInput.focus();
            searchInput.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }
    }
});
